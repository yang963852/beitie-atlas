/**
 * Read-only status report for `knowledge/`.
 *
 * The report is built from the compiled interface and the validator's
 * warnings, so it cannot invent a fourth definition of a citation or date
 * rule. `npm run knowledge:status` writes `docs/knowledge-status.md`;
 * `--check` fails when the generated page is stale.
 */

import { dynastyLabel, dynastyOrder } from '../../src/domain/dynasties';
import { dateSortValue } from '../../src/domain/dates';
import type { ReviewState, Work } from '../../src/domain/types';
import type { ValidationIssue } from '../../src/domain/validate';
import type { CompiledKnowledge } from './knowledge-compiler';

export const STATUS_PATH = 'docs/knowledge-status.md';
export const statusMarker =
  '<!-- Generated by npm run knowledge:status. Edit the source records, not this page. -->';

export interface WorkStatusRow {
  id: string;
  titleZh: string;
  period: string;
  review: ReviewState;
  guide: ReviewState | null;
  people: number;
  sources: number;
  objects: number;
  placesReferenced: number;
  placesWithCoordinates: number;
  dateGaps: number;
}

export interface ReviewTally {
  reviewed: number;
  draft: number;
}

export interface KnowledgeStatusReport {
  counts: CompiledKnowledge['counts'];
  review: {
    works: ReviewTally;
    objects: ReviewTally;
    articles: ReviewTally;
  };
  sourceUse: {
    none: number;
    single: number;
    multiple: number;
  };
  reviewedWorksWithSingleSource: number;
  attribution: {
    rows: number;
    linked: number;
  };
  dateGaps: number;
  uncitedSources: string[];
  unusedPlaces: string[];
  placesWithCoordinates: number;
  objectsWithEvents: number;
  works: WorkStatusRow[];
}

function tallyReviews<T>(items: T[], state: (item: T) => ReviewState): ReviewTally {
  const tally: ReviewTally = { reviewed: 0, draft: 0 };
  for (const item of items) tally[state(item)] += 1;
  return tally;
}

function warningIds(warnings: ValidationIssue[], code: string): string[] {
  const ids: string[] = [];
  for (const warning of warnings) {
    if (warning.code !== code) continue;
    const id = /"([^"]+)"/.exec(warning.message)?.[1];
    if (id) ids.push(id);
  }
  return ids.sort();
}

function dateGapIndex(
  knowledge: CompiledKnowledge,
  warnings: ValidationIssue[],
): { total: number; byWork: Map<string, number> } {
  const byWork = new Map<string, number>();
  let total = 0;
  for (const warning of warnings) {
    if (warning.code !== 'DATE_WITHOUT_ORIGINAL') continue;
    total += 1;
    const match = /^\$\.(works|objects)\[(\d+)\]/.exec(warning.path);
    if (!match) continue;
    const [, collection, indexText] = match;
    if (!collection || !indexText) continue;
    const index = Number(indexText);
    const workId = collection === 'works'
      ? knowledge.works[index]?.id
      : knowledge.objects[index]?.workId;
    if (!workId) continue;
    byWork.set(workId, (byWork.get(workId) ?? 0) + 1);
  }
  return { total, byWork };
}

/** Person records reachable from a work through an explicit person link. */
function linkedPeople(work: Work, knowledge: CompiledKnowledge): number {
  const ids = new Set<string>();
  for (const attribution of work.attribution) {
    if (attribution.personId) ids.add(attribution.personId);
  }
  const guide = knowledge.articles.find((article) => article.kind === 'works' && article.id === work.id);
  for (const id of guide?.people ?? []) ids.add(id);
  for (const article of knowledge.articles) {
    if (article.kind === 'people' && article.works.includes(work.id)) ids.add(article.id);
  }
  return ids.size;
}

/** Places named by the work's objects; modern reference landmarks are excluded. */
function placeCoverage(work: Work, knowledge: CompiledKnowledge): { referenced: number; withCoordinates: number } {
  const referenced = new Set<string>();
  for (const object of knowledge.objects) {
    if (object.workId !== work.id) continue;
    if (object.currentCollection.placeId) referenced.add(object.currentCollection.placeId);
    for (const event of object.provenanceEvents) {
      if (event.placeId) referenced.add(event.placeId);
    }
  }
  const places = new Map(knowledge.places.map((place) => [place.id, place]));
  let withCoordinates = 0;
  for (const id of referenced) {
    if (places.get(id)?.coordinates) withCoordinates += 1;
  }
  return { referenced: referenced.size, withCoordinates };
}

export function buildKnowledgeStatus(
  knowledge: CompiledKnowledge,
  warnings: ValidationIssue[],
): KnowledgeStatusReport {
  const gaps = dateGapIndex(knowledge, warnings);
  const sourceUse = { none: 0, single: 0, multiple: 0 };
  for (const work of knowledge.works) {
    if (work.sourceRefs.length === 0) sourceUse.none += 1;
    else if (work.sourceRefs.length === 1) sourceUse.single += 1;
    else sourceUse.multiple += 1;
  }

  const works = [...knowledge.works]
    .sort(
      (a, b) =>
        dynastyOrder(a.dynastyId) - dynastyOrder(b.dynastyId) ||
        dateSortValue(a.compositionDate) - dateSortValue(b.compositionDate) ||
        (a.id < b.id ? -1 : 1),
    )
    .map((work) => {
      const guide = knowledge.articles.find(
        (article) => article.kind === 'works' && article.id === work.id,
      );
      const coverage = placeCoverage(work, knowledge);
      return {
        id: work.id,
        titleZh: work.titles.zh,
        period: dynastyLabel(work.dynastyId, 'en', work.dynastyQualifier),
        review: work.review.state,
        guide: guide?.state ?? null,
        people: linkedPeople(work, knowledge),
        sources: work.sourceRefs.length,
        objects: knowledge.objects.filter((object) => object.workId === work.id).length,
        placesReferenced: coverage.referenced,
        placesWithCoordinates: coverage.withCoordinates,
        dateGaps: gaps.byWork.get(work.id) ?? 0,
      };
    });

  return {
    counts: knowledge.counts,
    review: {
      works: tallyReviews(knowledge.works, (work) => work.review.state),
      objects: tallyReviews(knowledge.objects, (object) => object.review.state),
      articles: tallyReviews(knowledge.articles, (article) => article.state),
    },
    sourceUse,
    reviewedWorksWithSingleSource: knowledge.works.filter(
      (work) => work.review.state === 'reviewed' && work.sourceRefs.length === 1,
    ).length,
    attribution: {
      rows: knowledge.works.reduce((sum, work) => sum + work.attribution.length, 0),
      linked: knowledge.works.reduce(
        (sum, work) => sum + work.attribution.filter((entry) => entry.personId).length,
        0,
      ),
    },
    dateGaps: gaps.total,
    uncitedSources: warningIds(warnings, 'UNUSED_SOURCE'),
    unusedPlaces: warningIds(warnings, 'UNUSED_PLACE'),
    placesWithCoordinates: knowledge.places.filter((place) => place.coordinates).length,
    objectsWithEvents: knowledge.objects.filter((object) => object.provenanceEvents.length > 0).length,
    works,
  };
}

function cell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function ids(values: string[]): string {
  return values.length ? values.map((value) => '`' + value + '`').join(', ') : '—';
}

export function renderStatusMarkdown(report: KnowledgeStatusReport): string {
  const counts = report.counts;
  const guidesByState = report.works.reduce(
    (tally, work) => {
      if (work.guide === 'reviewed') tally.reviewed += 1;
      if (work.guide === 'draft') tally.draft += 1;
      return tally;
    },
    { reviewed: 0, draft: 0 },
  );
  const lines = [
    statusMarker,
    '',
    '# Knowledge status',
    '',
    'Generated from `data/index/knowledge-v1.json` and the validator warnings. Edit the records under `knowledge/` and rerun `npm run knowledge:status`; do not hand-edit this page.',
    '',
    '## Summary',
    '',
    '| Measure | Value |',
    '| --- | --- |',
    `| Works | ${counts.works} (${report.review.works.reviewed} reviewed / ${report.review.works.draft} draft) |`,
    `| Objects | ${counts.objects} (${report.review.objects.reviewed} reviewed / ${report.review.objects.draft} draft) |`,
    `| Guides | ${counts.workArticles} (${guidesByState.reviewed} reviewed / ${guidesByState.draft} draft) |`,
    `| People pages | ${counts.peopleArticles} |`,
    `| Notes | ${counts.noteArticles} |`,
    `| Places | ${counts.places} (${report.placesWithCoordinates} with coordinates) |`,
    `| Sources | ${counts.sources} (${report.uncitedSources.length} uncited) |`,
    `| Events | ${counts.events} (${report.objectsWithEvents} objects with events) |`,
    `| Attribution entries linked to a person | ${report.attribution.linked} / ${report.attribution.rows} |`,
    `| Work sources (0 / 1 / 2+) | ${report.sourceUse.none} / ${report.sourceUse.single} / ${report.sourceUse.multiple} |`,
    `| Reviewed works with one source | ${report.reviewedWorksWithSingleSource} |`,
    `| Dates without source wording | ${report.dateGaps} |`,
    '',
    '## Gaps',
    '',
    `- Uncited sources: ${ids(report.uncitedSources)}`,
    `- Unused places: ${ids(report.unusedPlaces)}`,
    '',
    '## Works',
    '',
    '| Work | Period | Review | Guide | People | Sources | Objects | Places | Date gaps |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...report.works.map((work) => {
      const link = `[${cell(work.titleZh)}](../knowledge/works/${work.id}.md)`;
      const places = work.placesReferenced === 0
        ? '—'
        : `${work.placesWithCoordinates}/${work.placesReferenced}`;
      return `| ${link} | ${cell(work.period)} | ${work.review} | ${work.guide ?? '—'} | ${work.people} | ${work.sources} | ${work.objects} | ${places} | ${work.dateGaps || '—'} |`;
    }),
    '',
    'People counts distinct person records reachable from the work through an attribution `personId`, its guide or a person page. Places shows places with a recorded coordinate out of the places named by the work\'s objects; modern reference landmarks are excluded. Date gaps count `DATE_WITHOUT_ORIGINAL` warnings from the validator.',
    '',
  ];
  return lines.join('\n');
}
