export const generatedMarker = '<!-- Generated by npm run knowledge:generate. Edit the linked source records. -->';
const correction = 'https://github.com/yang963852/beitie-atlas/issues/new?template=knowledge.yml';
const website = 'https://yang963852.github.io/beitie-atlas/';
const state = (value: ReviewState) => value === 'reviewed' ? '已审' : '待审';
const label = (value: string) => value.replace(/([\\[\]])/g, '\\$1');
const link = (title: string, target: string) => '[' + label(title) + '](' + target + ')';
const articleLink = (article: KnowledgeArticle, prefix = '') =>
  link(article.titleZh, prefix + article.kind + '/' + article.id + '.md');
const date = (value: HistoricalDate) => value.original || formatDate(value, 'zh');

function renderWork(work: Work, data: Dataset, articles: KnowledgeArticle[]): string {
  const refs = new Map<string, number>();
  function cite(ids: string[]): string {
    return ids.map(id => {
      if (!refs.has(id)) refs.set(id, refs.size + 1);
      return link('出处 ' + refs.get(id), '#ref-' + id);
    }).join('、');
  }
  const related = articles.filter(a => a.works.includes(work.id) || (a.kind === 'works' && a.id === work.id));
  const issue = correction + '&title=' + encodeURIComponent('【资料勘误】' + work.titles.zh + ' · ' + work.id);
  const lines = [generatedMarker, '', '# ' + work.titles.zh, '', '[返回知识总目](../README.md) · [提交勘误](' + issue + ')', '',
    work.titles.en, '', '**作品**　' + dynastyLabel(work.dynastyId, 'zh', work.dynastyQualifier) + ' · '
      + date(work.compositionDate) + ' · ' + (work.studyCategory === 'bei' ? '碑' : '帖') + ' · ' + state(work.review.state), '',
    work.backgroundZh || work.background, '', cite(work.sourceRefs), ''];
  for (const a of work.attribution) {
    lines.push('- ' + labels.attributionRoleLabels[a.role] + ' · ' + a.name + '（' + labels.certaintyLabels[a.certainty] + '） '
      + (a.noteZh || a.note || '') + ' ' + cite(a.sourceRefs));
  }
  if (work.aliases.length) lines.push('', '别名：' + work.aliases.join('、'));
  if (work.script) lines.push('', '书体：' + work.script);
  if (related.length) lines.push('', '延伸阅读：' + related.map(a => articleLink(a, '../')).join(' · '));
  if (work.notes.length) lines.push('', '作品待考与说明', '', ...(work.notesZh || work.notes).map(text => '- ' + text));
  const objects = data.objects.filter(o => o.workId === work.id);
  for (const object of objects) {
    const holding = object.currentCollection;
    const place = data.places.find(p => p.id === holding.placeId);
    lines.push('', '<a name="' + object.id + '"></a>', '', '## ' + object.titles.zh, '',
      object.titles.en, '', labels.objectTypeLabels[object.objectType] + ' · ' + labels.survivalLabels[object.survivalStatus]
        + ' · ' + state(object.review.state), '',
      '- 制作年代：' + date(object.productionDate),
      '- 著录编号：' + (object.catalogNumber || '未记录'),
      '- 尺寸：' + (object.dimensions?.raw || '未记录'),
      '- ' + labels.locationKindLabels[holding.locationKind] + (place ? '：' + place.names.zh : '') + '　' + cite(holding.sourceRefs),
      '- 所引来源查阅于 ' + holding.sourceAccessedAt + (holding.assertionAsOf ? '。来源所述时间为 ' + holding.assertionAsOf : ''),
      '', holding.noteZh || holding.note || '', '', '### 递藏与流传', '');
    if (!object.provenanceEvents.length) lines.push(labels.provenanceEmpty);
    for (const event of object.provenanceEvents) {
      const location = event.placeWording || data.places.find(p => p.id === event.placeId)?.names.zh;
      const reference = data.places.find(p => p.id === event.referencePlaceId);
      lines.push('- ' + date(event.date) + ' · ' + labels.eventTypeLabels[event.type]
        + (location ? ' · ' + location : '') + '（' + labels.certaintyLabels[event.certainty] + '）　'
        + (event.summaryZh || event.summary) + ' ' + cite(event.sourceRefs)
        + (reference ? '　今日参照地标：' + reference.names.zh + '（不是事件发生地）' : ''));
    }
    const relationNames = { 'rubbing-of': '拓自', 'recarving-of': '翻刻自', 'fragment-of': '残件所属' };
    for (const relation of object.relationships) {
      const target = data.objects.find(o => o.id === relation.targetObjectId)!;
      lines.push('', relationNames[relation.type] + '：' + link(target.titles.zh, target.workId + '.md#' + target.id)
        + ' ' + cite(relation.sourceRefs));
    }
    if (object.notes.length) lines.push('', '### 实物待考与说明', '', ...(object.notesZh || object.notes).map(text => '- ' + text));
    lines.push('', link('在图鉴中查看这件实物', website + '#/object/' + object.id)
      + ' · ' + link('实物源稿', '../../knowledge/objects/' + object.id + '.md'));
  }
  lines.push('', '## 据以著录的来源', '');
  for (const [id, number] of refs) {
    const s = data.sources.find(s => s.id === id)!;
    const title = s.url ? link(s.title, '<' + s.url + '>') : s.title;
    lines.push('<a name="ref-' + id + '"></a>', '', number + '. ' + s.publisher + ' · ' + title
      + (s.publicationDate ? '（' + s.publicationDate + '）' : '') + (s.locator ? '。定位：' + s.locator : '')
      + '。查阅于 ' + s.accessedAt + '。', '');
  }
  lines.push(link('作品源稿', '../../knowledge/works/' + work.id + '.md') + ' · [返回知识总目](../README.md)');
  return lines.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}

export function cataloguePages(data: Dataset, articles: KnowledgeArticle[]): Map<string, string> {
  const files = new Map<string, string>();
  const stableId = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
  for (const row of [...data.works, ...data.objects, ...data.sources]) {
    if (!stableId.test(row.id)) throw new Error('Invalid ID for Markdown projection: ' + row.id);
  }
  const index = [generatedMarker, '', '# 碑帖之间 · 知识总目', '',
    '从作品、书家或版本笔记入手，也可按时代查找传世实物。标为「待审」的内容仍在编辑中。本页与 `catalogue/` 由 `knowledge/` 源稿生成，不要手改。', '',
    '[打开网页知识库](' + website + '#/library) · [下载完整知识库](https://yang963852.github.io/beitie-atlas/download/beitie-knowledge.zip) · [提交中文资料或勘误](' + correction + ') · [中文贡献指南](../docs/CONTRIBUTE.zh-CN.md)'];
  for (const [kind, name] of [['works', '作品导读'], ['people', '书家'], ['notes', '考证与读帖笔记']] as const) {
    index.push('', '## ' + name, '');
    for (const a of articles.filter(a => a.kind === kind)) index.push('- ' + articleLink(a) + ' · ' + state(a.state));
  }
  index.push('', '## 作品与实物档案', '',
    '依作品所属时代编排。进入每件实物可查制作年代、收藏依据、流传记录、出处和仍待考证之处。');
  const works = [...data.works].sort((a, b) => dynastyOrder(a.dynastyId) - dynastyOrder(b.dynastyId)
    || dateSortValue(a.compositionDate) - dateSortValue(b.compositionDate) || (a.id < b.id ? -1 : 1));
  let period = '';
  for (const work of works) {
    if (period !== work.dynastyId) {
      period = work.dynastyId;
      index.push('', '### ' + dynastyLabel(work.dynastyId, 'zh'), '');
    }
    const path = 'catalogue/' + work.id + '.md';
    const count = data.objects.filter(o => o.workId === work.id).length;
    index.push('- ' + link(work.titles.zh, path) + ' · ' + count + ' 件实物 · ' + state(work.review.state));
    files.set(path, renderWork(work, data, articles));
  }
  files.set('README.md', index.join('\n') + '\n');
  return files;
}
